#include <limits.h>
#include "stdio.h"

void	putnbr(int n)
{
	char	c;

	if (n == INT_MIN)
	{
		puts("-2147483648");
		return ;
	}
	if (n < 0)
	{
		putchar('-');
		n *= -1;
	}
	if (n <= 9)
	{
		c = n + '0';
		putchar(c);
	}
	else
	{
		putnbr(n / 10);
		c = n % 10 + '0';
		putchar(c);
	}
}
